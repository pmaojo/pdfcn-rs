#!/usr/bin/env python3
"""Regenerates pdfcn-components/src/icons/data.rs from scripts/icons.txt.

    npm pack @tabler/icons@<version>
    tar xzf tabler-icons-<version>.tgz        # unpacks to ./package
    python3 scripts/update-icons.py ./package

Each icon keeps only its drawing (the children of the <svg>); the wrapper, the
colour and the stroke width are put back at render time, which is what lets
`%Icon` take `color` and `stroke`. The upstream background square
(`<path stroke="none" d="M0 0h24v24H0z" fill="none"/>`) is dropped.
"""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
package = pathlib.Path(sys.argv[1])
names = [l.strip() for l in (root / "scripts/icons.txt").read_text().splitlines() if l.strip() and not l.startswith("#")]
version = json.loads((package / "package.json").read_text())["version"]
assert len(names) == len(set(names)), "duplicate names in icons.txt"

out = [
    "// @generated by scripts/update-icons.py from Tabler Icons %s (MIT, (c) Pawel Kuna)." % version,
    "// Do not edit by hand: change scripts/icons.txt and regenerate.",
    "",
    "/// Tabler Icons release the drawings below come from.",
    'pub(crate) const TABLER_VERSION: &str = "%s";' % version,
    "",
    "/// `(name, children of the 24x24 outline <svg>)`, sorted by name.",
    "pub(crate) const ICONS: &[(&str, &str)] = &[",
]
missing = []
for name in sorted(names):
    f = package / "icons" / "outline" / (name + ".svg")
    if not f.exists():
        missing.append(name); continue
    svg = f.read_text()
    body = svg[svg.index(">", svg.index("<svg")) + 1 : svg.rindex("</svg>")]
    body = re.sub(r'<path\s+stroke="none"\s+d="M0 0h24v24H0z"\s+fill="none"\s*/>', "", body)
    body = re.sub(r"\s+", " ", body).strip()
    body = re.sub(r"\s*/>", "/>", body)
    assert "##" not in body and "<script" not in body
    out.append('    ("%s", r##"%s"##),' % (name, body))
out.append("];")
if missing:
    sys.exit("not in Tabler %s: %s" % (version, ", ".join(missing)))
(root / "pdfcn-components/src/icons/data.rs").write_text("\n".join(out) + "\n")
print("wrote %d icons (Tabler %s)" % (len(names), version))
